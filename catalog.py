"""Каталог мотивации для Reward Tracker.

Логика разделена на:
1) базовые вознаграждения за тип основной встречи;
2) дополнительные оферы, которые можно добавлять к встрече (по группам);
3) быстрые оферы (Смарт, Доп. тревел) — добавляются одним нажатием, без
   подменю и без ручного ввода сумм.

Смарт и страховка пишутся в отчёт за сегодня в день продажи, а в
официальную статистику месяца попадают только 1-го числа следующего
месяца (см. payout_date_for). Отчёты показывают сумму «со Смарт/страховкой»
и «без» — см. reports.py.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class Offer:
    code: str
    group: str
    name: str
    condition: str
    reward: int
    deferred: bool = False


def next_month_first(iso_date: str) -> str:
    year, month, _ = (int(part) for part in iso_date.split("-"))
    month += 1
    if month == 13:
        year += 1
        month = 1
    return f"{year:04d}-{month:02d}-01"


def payout_date_for(offer: Offer, meeting_date: str) -> str | None:
    if offer.deferred:
        return next_month_first(meeting_date)
    return None


